using System.ComponentModel;
using System.Reflection;
using System.Text.RegularExpressions;
using ModelContextProtocol.Server;
using VPanel.Core.Abstractions;
using VPanel.Core.Configuration;
using VPanel.Core.Domain;
using VPanel.Core.Utilities;
using VPanel.Infrastructure.Docker;
using VPanel.Infrastructure.Services;

namespace VPanel.Web.Mcp;

[McpServerToolType]
public sealed partial class PanelTools(SettingsService settings, InstanceService instances, AppTypeRegistry registry)
{
    internal static readonly ManagedVariableDto[] ManagedVariables =
    [
        new("VPANEL_INSTANCE", "Instance slug, e.g. myapp-01"),
        new("VPANEL_INSTANCE_NAME", "Instance display name"),
        new("VPANEL_APP", "App slug"),
        new("VPANEL_PUBLIC_URL", "Public URL of the instance without trailing slash (empty when not set)"),
        new("VPANEL_HOST", "Host name of the Public URL"),
        new("VPANEL_SHARED_NETWORK", "External docker network shared with Caddy and Postgres"),
        new("VPANEL_INSTALL_PATH", "Install folder of the instance (holds docker-compose.yml)"),
        new("VPANEL_PROXY_ALIAS", "DNS name of the proxied service on the shared network: vp-<instance>-<service>"),
        new("VPANEL_CADDY_DIR", "Host folder with the Caddy configuration"),
        new("COMPOSE_PROJECT_NAME", "vp-<instance>; named volumes are prefixed with it"),
    ];

    [McpServerTool(Name = "get_panel_info", ReadOnly = true, Idempotent = true, OpenWorld = false)]
    [Description("Server facts needed to write a compose file for v-panel: apps root, shared docker network, ingress mode (Cloudflare Tunnel or Direct), managed VPANEL_* variables, shared services and the system instances.")]
    public async Task<PanelInfo> GetPanelInfo(CancellationToken ct)
    {
        var s = settings.Get();
        var system = (await instances.ListAsync(ct: ct)).Where(i => i.Instance.App!.IsSystem).Select(InstanceTools.ToListItem).ToList();
        var notes = new List<string>
        {
            s.Ingress == IngressMode.CloudflareTunnel
                ? "Ingress is Cloudflare Tunnel: TLS ends at Cloudflare, Caddy serves plain HTTP and publishes no ports. Each Public URL hostname must be added to the tunnel (Service HTTP, URL caddy:80) unless a wildcard hostname exists."
                : "Ingress is Direct: Caddy publishes ports 80/443 and obtains certificates; DNS of each Public URL host must point to this server.",
            "Only the instance's proxy service is attached to the shared network automatically; other services that need the shared Postgres must join it explicitly.",
        };
        if (!s.CaddyEnabled) notes.Add("Caddy integration is disabled in Settings: Public URLs are not routed automatically.");
        return new PanelInfo(
            typeof(PanelTools).Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion ?? "dev",
            s.AppsRoot, s.SharedNetwork, s.Ingress.ToString(), s.CaddyEnabled, s.PanelPublicUrl,
            ManagedVariables,
            [
                new SharedServiceDto("postgres", 5432, "Shared PostgreSQL 18 (shared-infra). Superuser credentials are in the shared-infra app env (POSTGRES_USER / POSTGRES_PASSWORD); create one database and role per instance."),
                new SharedServiceDto(s.CaddyContainer, 80, "Shared Caddy reverse proxy; routes are generated by v-panel from Public URLs."),
            ],
            system, notes);
    }

    [McpServerTool(Name = "get_install_guide", ReadOnly = true, Idempotent = true, OpenWorld = false)]
    [Description("Conventions and step-by-step workflow for installing an application (e.g. from a GitHub repository) so that v-panel manages it. Read this before creating or changing apps.")]
    public string GetInstallGuide() => McpGuide.InstallGuide;

    [McpServerTool(Name = "validate_compose", ReadOnly = true, Idempotent = true, OpenWorld = false)]
    [Description("Offline validation of a docker-compose.yml (+ optional .env) against v-panel rules, without saving anything. Returns errors, warnings and the parsed services, volumes and external networks. docker compose config runs again at deploy time.")]
    public ComposeReport ValidateCompose(
        [Description("Full docker-compose.yml content.")] string compose,
        [Description("Optional .env content (KEY=value lines) used for variable interpolation.")] string? env = null,
        [Description("Service that will receive HTTP traffic (to check it exists).")] string? proxy_service = null) =>
        Check(registry, compose, env, proxy_service);

    internal static ComposeReport Check(AppTypeRegistry registry, string compose, string? env, string? proxyService)
    {
        // Same validation as the editor/deploy, plus advice specific to running behind v-panel's Caddy.
        var report = registry.Get(AppType.DockerCompose).Validate(compose, env ?? "");
        var analysis = ComposeAnalyzer.Analyze(compose, EnvFile.Parse(env).ToDictionary());
        var extra = report.Issues.Where(i => !analysis.Issues.Contains(i)).ToList();
        extra.AddRange(Advice(analysis, compose, proxyService));
        return ComposeReport.From(analysis, extra);
    }

    [GeneratedRegex(@"^\s+container_name\s*:", RegexOptions.Multiline)]
    private static partial Regex ContainerNameRegex();

    private static IEnumerable<ValidationIssue> Advice(ComposeAnalysis analysis, string compose, string? proxyService)
    {
        foreach (var s in analysis.Services.Where(s => s.Ports.Count > 0))
            yield return new ValidationIssue(
                $"Service '{s.Name}' publishes host ports ({string.Join(", ", s.Ports)}). v-panel routes HTTP through Caddy on the shared network; remove 'ports' unless the port must be reachable directly (it also prevents running two instances).",
                IsWarning: true);
        if (ContainerNameRegex().IsMatch(compose))
            yield return new ValidationIssue("'container_name' makes container names collide between instances; let compose name containers from the project.", IsWarning: true);
        if (!string.IsNullOrWhiteSpace(proxyService) && analysis.Services.Count > 0)
        {
            var svc = analysis.Services.FirstOrDefault(s => s.Name == proxyService.Trim());
            if (svc is null)
                yield return new ValidationIssue($"Proxy service '{proxyService}' is not defined in the compose file.", IsWarning: true);
            else if (svc.NetworkMode is not null)
                yield return new ValidationIssue($"Proxy service '{proxyService}' uses network_mode and cannot be attached to the shared network.", IsWarning: true);
        }
    }
}
